#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Expected Parrot HTML File Collection Script

Automatically collects all HTML files generated by Expected Parrot into ep_html folder
after each experiment round. Files are organized by experiment directory and round number.

Usage:
1. Call this script after each round in main.py
2. Or run manually: python collect_ep_html.py [experiment_dir] [round_num]
"""

import os
import shutil
import glob
from pathlib import Path
import argparse
from datetime import datetime


def collect_ep_html_files(base_dir=None):
    """
    Collect HTML files generated by Expected Parrot
    
    Args:
        base_dir: Base directory (defaults to current directory)
    """
    if base_dir is None:
        base_dir = Path.cwd()
    else:
        base_dir = Path(base_dir)
    
    # Create ep_html directory in root (base_dir)
    ep_html_dir = base_dir / "ep_html"
    ep_html_dir.mkdir(exist_ok=True)
    
    # Find all Expected Parrot HTML files (tmp*.html and output.html)
    tmp_files = list(base_dir.glob("tmp*.html"))
    output_files = list(base_dir.glob("output.html"))
    html_files = tmp_files + output_files
    
    if not html_files:
        print("[INFO] No Expected Parrot HTML files found")
        return True
    
    print(f"[INFO] Found {len(html_files)} HTML files")
    
    collected_count = 0
    
    for html_file in html_files:
        try:
            # Get file modification time for timestamp
            file_mtime = datetime.fromtimestamp(html_file.stat().st_mtime)
            
            # Generate new filename with timestamp
            timestamp = file_mtime.strftime("%Y%m%d_%H%M%S")
            new_filename = f"{html_file.stem}_{timestamp}.html"
            target_path = ep_html_dir / new_filename
            
            # Move file
            shutil.move(str(html_file), str(target_path))
            print(f"[INFO] Moved: {html_file.name} -> {target_path.relative_to(base_dir)}")
            collected_count += 1
            
        except Exception as e:
            print(f"[ERROR] Failed to process file {html_file.name}: {e}")
    
    print(f"[INFO] Successfully collected {collected_count} HTML files to {ep_html_dir.relative_to(base_dir)}")
    return True




def main():
    """Main function"""
    parser = argparse.ArgumentParser(description='Collect HTML files generated by Expected Parrot')
    parser.add_argument('--base-dir', '-b', type=str, help='Base directory (defaults to current directory)')
    
    args = parser.parse_args()
    
    print("[INFO] Starting Expected Parrot HTML file collection...")
    
    success = collect_ep_html_files(args.base_dir)
    
    if success:
        print("[INFO] HTML file collection completed successfully!")
        return 0
    else:
        print("[ERROR] HTML file collection failed!")
        return 1


if __name__ == "__main__":
    exit(main())
